def js_str(s):
    return s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")


def emit():
    lines = []
    lines.append("(function () {")
    lines.append("  var set = window.COPY_SET;")
    lines.append("  if (!set) return;")
    lines.append("  function S(series, title, cover, body, tags, comment) {")
    lines.append("    return { type: \"软文\", series: series, title: title, cover: cover, body: body, tags: tags, comment: comment };")
    lines.append("  }")
    lines.append("  function H(series, title, cover, body, tags, comment) {")
    lines.append("    return { type: \"硬广\", series: series, title: title, cover: cover, body: body, tags: tags, comment: comment };")
    lines.append("  }")
    lines.append("  function day(date, weekday, a, b, h) {")
    lines.append("    a.time = \"08:22\"; b.time = \"12:18\"; h.time = \"20:25\";")
    lines.append("    set.daysData.push({ date: date, weekday: weekday, slots: [a, b, h] });")
    lines.append("  }")
    n = 20
    d = date(2026, 11, 22)
    end = date(2026, 12, 31)
    i = 0
    missing = []
    cursor = d
    while cursor <= end:
        if cursor.isoformat() not in HARD:
            missing.append(cursor.isoformat())
        cursor += timedelta(days=1)
    assert not missing, missing
    while d <= end:
        s1 = SOFT[i]
        s2 = SOFT[i + 1]
        i += 2
        wd = WD[d.weekday()]
        h = HARD[d.isoformat()]

        def soft_call(tup, num):
            figure, persona, title, hl, body, tags, comment = tup
            series = "人格图鉴 %02d · %s" % (num, persona)
            cover = "主标：%s\\n高亮：%s\\n极简卡通" % (title, hl)
            return 'S("%s", "%s", "%s", "%s", "%s", "%s")' % (
                js_str(series), js_str(title), cover, js_str(body), js_str(tags), js_str(comment),
            )

        hcall = "H(\"%s\", \"%s\", \"%s\", \"%s\", \"%s\", \"%s\")" % tuple(
            js_str(x) for x in h
        )

        lines.append(
            '  day("%s", "%s", %s, %s, %s);'
            % (d.isoformat(), wd, soft_call(s1, n), soft_call(s2, n + 1), hcall)
        )
        n += 2
        d += timedelta(days=1)

    assert i == 80, i
    lines.append("  set.from = \"2026-11-15\";")
    lines.append("  set.note = \"每天 8:22 软文 / 12:18 软文 / 20:25 硬广。软文不挂商品。预备到 2026-12-31。\";")
    lines.append("})();")
    out = Path(__file__).resolve().parents[1] / "js" / "data-winter.js"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("wrote", out, "days", 40, "soft", 80)


if __name__ == "__main__":
    emit()
